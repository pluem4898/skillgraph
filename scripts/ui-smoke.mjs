import { chromium } from 'playwright-core';
import { mkdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const base = process.env.SKILLGRAPH_URL || 'http://127.0.0.1:4318';
const browser = await chromium.launch({ executablePath: process.env.EDGE_PATH || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true });
const errors = [];
const checks = [];
mkdirSync('reports', { recursive: true });
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
  page.setDefaultTimeout(30_000);
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(base, { waitUntil: 'networkidle' });
  assert.equal(await page.locator('html').getAttribute('lang'), 'en');
  await page.locator('.skill-card').first().waitFor();
  assert.ok(Number((await page.locator('#stat-skills').innerText()).replaceAll(',', '')) > 0);
  checks.push('Live corpus statistics and complete first list page render');
  const scoped = await (await fetch(`${base}/api/skills?repository=openai%2Fskills&limit=1`)).json();
  await page.locator('#repository').selectOption('openai/skills');
  await page.waitForFunction(expected => document.querySelector('#catalog-total').textContent === `${expected} skills`, scoped.total, { timeout: 30_000 });
  await page.locator('.skill-card').first().click();
  await page.locator('#source-content .line-row').first().waitFor();
  assert.ok((await page.locator('#source-path').innerText()).includes('openai/skills'));
  checks.push('Explicit repository scope and immutable numbered source read');
  await page.locator('#list-next').click();
  await page.waitForFunction(() => document.querySelector('#list-range').textContent.startsWith('31'), null, { timeout: 30_000 });
  assert.equal(await page.locator('.skill-card').count(), scoped.total - 30);
  checks.push('Last catalog page retains all remaining occurrences across source snapshots');
  await page.locator('#open-catalog').click();
  await page.waitForFunction(() => document.querySelector('#catalog-preview').textContent.includes('handle'), null, { timeout: 30_000 });
  const compact = await page.locator('#catalog-preview').innerText();
  assert.equal(compact.trimEnd().split('\n').length, scoped.total + 1);
  await page.locator('#catalog-format').selectOption('full');
  await page.locator('#catalog-options').evaluate(form => form.requestSubmit());
  await page.waitForFunction(() => document.querySelector('#catalog-preview').textContent.startsWith('["id"'), null, { timeout: 30_000 });
  assert.equal((await page.locator('#catalog-preview').innerText()).trimEnd().split('\n').length, scoped.total + 1);
  checks.push('Compact and full exports preserve every scoped catalog entry');
  await page.locator('#close-catalog').click();
  await page.locator('#experiments-tab').click();
  await page.locator('#experiment-scope').waitFor({ timeout: 30000 });
  assert.ok((await page.locator('#report-content').innerText()).includes('40,541'));
  assert.ok((await page.locator('#report-content').innerText()).includes('3,135,249'));
  checks.push('Actual benchmark summary and compact transport measurements render');
  await page.screenshot({ path: 'reports/experiments.png', fullPage: true });
  await page.locator('#explore-tab').click();
  await page.screenshot({ path: 'reports/explorer.png', fullPage: true });
  const desktopOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(desktopOverflow, false);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'reports/mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  checks.push('Desktop and mobile layouts do not overflow the viewport');
  assert.deepEqual(errors, []);
  writeFileSync('reports/ui-smoke.json', JSON.stringify({ checkedAt: new Date().toISOString(), base, browser: 'installed Microsoft Edge, headless', checks, errors, status: 'passed' }, null, 2));
  console.log(JSON.stringify({ status: 'passed', checks: checks.length, errors }));
} catch (error) {
  writeFileSync('reports/ui-smoke.json', JSON.stringify({ checkedAt: new Date().toISOString(), base, checks, errors, status: 'failed', failure: String(error) }, null, 2));
  throw error;
} finally { await browser.close(); }
